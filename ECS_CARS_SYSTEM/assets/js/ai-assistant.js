// ===== Initialize Chat =====
function initChat() {
    if (!chatContainer || !userInput || !sendBtn) return;
    
    // Add welcome message
    addMessage('ai', `Привет! Я ИИ-ассистент по китайским электромобилям. 🚗⚡
    
    Я могу ответить на вопросы о:
    • Китайских брендах электромобилей (BYD, NIO, XPeng и др.)
    • Технических характеристиках и особенностях
    • Применяемых запчастях
    • Методах решения программных вопросов
    • Ценах и доступности
    
    Задайте мне вопрос!`);
    
    // Send button click
    sendBtn.addEventListener('click', sendMessage);
    
    // Enter key press
    userInput.addEventListener('keypress', function(e) {
        if (e.key === 'Enter') {
            sendMessage();
        }
    });
}

// ===== Send Message =====
function sendMessage() {
    const question = userInput.value.trim();
    if (!question) return;
    
    // Add user message
    addMessage('user', question);
    userInput.value = '';
    
    // Show typing indicator
    const typingIndicator = addMessage('ai', '<i class="fas fa-ellipsis-h fa-spin"></i>', true);
    
    // Simulate API call delay
    setTimeout(() => {
        // Remove typing indicator
        typingIndicator.remove();
        
        // Get response
        const response = getAIResponse(question);
        addMessage('ai', response);
    }, 500);
}

// ===== Get AI Response =====
function getAIResponse(question) {
    const normalizedQuestion = question.toLowerCase().trim();
    
    // Check knowledge base
    for (const [key, value] of Object.entries(knowledgeBase)) {
        if (normalizedQuestion.includes(key)) {
            return value.response;
        }
    }
    
    // Check for similar questions
    const similarQuestions = {
        'byd': knowledgeBase['расскажи про byd'].response,
        'nio': knowledgeBase['расскажи про nio'].response,
        'xpeng': knowledgeBase['расскажи про xpeng'].response,
        'blade': knowledgeBase['что такое blade battery'].response,
        'power swap': knowledgeBase['что такое nio power swap'].response,
        'xngp': knowledgeBase['что такое xngp'].response,
        'зарядка': knowledgeBase['как заряжать китайский электромобиль'].response,
        'запчасти': knowledgeBase['какие запчасти используются в электромобилях'].response,
        'преимущества': knowledgeBase['какие преимущества у китайских электромобилей'].response
    };
    
    for (const [key, response] of Object.entries(similarQuestions)) {
        if (normalizedQuestion.includes(key)) {
            return response;
        }
    }
    
    // Default response
    return knowledgeBase['default'].response;
}

// ===== Add Message to Chat =====
function addMessage(sender, message, isTyping = false) {
    const messageDiv = document.createElement('div');
    messageDiv.className = `chat-message ${sender}-message`;
    
    if (isTyping) {
        messageDiv.id = 'typing-indicator';
    }
    
    messageDiv.innerHTML = message;
    chatContainer.appendChild(messageDiv);
    
    // Scroll to bottom
    chatContainer.scrollTop = chatContainer.scrollHeight;
    
    return messageDiv;
}

// ===== Clear Chat =====
function clearChat() {
    chatContainer.innerHTML = '';
}

// ===== Initialize =====
document.addEventListener('DOMContentLoaded', function() {
    initChat();
    
    // Close modal when clicking outside
    if (modal) {
        modal.addEventListener('click', function(e) {
            if (e.target === modal) {
                modal.classList.remove('active');
            }
        });
    }
});

// ===== Export for other scripts =====
window.AIAssistant = {
    initChat,
    sendMessage,
    clearChat,
    getAIResponse
};
